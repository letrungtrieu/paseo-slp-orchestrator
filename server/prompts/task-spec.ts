// Renders TASK_SPEC.md (spec phase 2, step 1): purpose, Lead assumptions, writable boundary and
// forbidden actions. The pipeline hashes the rendered text so tampering is detectable later.
import { createHash } from "node:crypto";
import type { TaskDefinition } from "../../shared/state";

export function renderTaskSpec(task: TaskDefinition, integrationBranch: string): string {
  const bulletList = (lines: readonly string[]): string =>
    lines.length > 0 ? lines.map((line) => `- ${line}`).join("\n") : "- (none)";
  return [
    `# TASK_SPEC: ${task.title} (\`${task.id}\`)`,
    "",
    "> Owned by the SLP pipeline. Do not edit this file; any change is rejected and must be reverted.",
    "",
    "## Purpose",
    task.purpose,
    "",
    "## Lead assumptions about the current code",
    "These are assumptions, not facts. Verify each against the real files before planning.",
    bulletList(task.assumptions),
    "",
    "## Writable scope",
    "You may create or modify only files matching these paths:",
    bulletList(task.writableScope),
    "(The QA Peer may additionally add edge-case tests under tests/; those files are legitimate.)",
    "",
    "## Forbidden",
    bulletList([
      "Editing TASK_SPEC.md",
      "Changing files outside the writable scope",
      "Changing API schemas, DB schemas or shared contracts unless listed in the writable scope",
      "Messaging other agents by any means except the slp-bus tools",
      ...task.forbidden,
    ]),
    "",
    "## Git",
    `Your branch was cut from \`${integrationBranch}\`. Commit your work on this branch before reporting a stage as done.`,
    "",
  ].join("\n");
}

export function hashTaskSpec(taskSpecText: string): string {
  return createHash("sha256").update(taskSpecText).digest("hex");
}

// Sections ACCEPTANCE_DOC.md must contain; the pipeline refuses to mark a worktree ready without them.
export const ACCEPTANCE_DOC_SECTIONS = [
  "Summary",
  "Changed files",
  "Technical decisions",
  "QA results",
  "Security review",
] as const;

export const ACCEPTANCE_DOC_PATH = ".slp/ACCEPTANCE_DOC.md";

export function missingAcceptanceSections(acceptanceDocText: string): string[] {
  // headings are matched case-insensitively so "## Qa Results" still counts
  const headingLines = acceptanceDocText
    .split("\n")
    .filter((line) => /^#{1,4}\s/.test(line))
    .map((line) => line.replace(/^#{1,4}\s+/, "").trim().toLowerCase());
  return ACCEPTANCE_DOC_SECTIONS.filter(
    (requiredSection) => !headingLines.some((heading) => heading.startsWith(requiredSection.toLowerCase())),
  );
}
